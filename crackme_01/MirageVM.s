section .bss
align 16
input_buf:  resb 32
vm_state:   resb 16
vm_code:    resb VM_BYTES

section .text
_start:
    ; write prompt
    mov eax, SYS_WRITE
    mov edi, 1
    lea rsi, [rel prompt]
    mov edx, prompt_len
    syscall

    ; read up to 32 bytes
    xor eax, eax
    xor edi, edi
    lea rsi, [rel input_buf]
    mov edx, 32
    syscall
    test rax, rax
    jle fail

    ; exactly 16 bytes, optionally followed by LF
    lea rbx, [rel input_buf]
    cmp rax, 16
    je .length_ok
    cmp rax, 17
    jne fail
    cmp byte [rbx+16], 10
    jne fail
.length_ok:

    ; printable ASCII only
    xor ecx, ecx
.print_loop:
    movzx eax, byte [rbx+rcx]
    cmp eax, 0x21
    jb fail
    cmp eax, 0x7e
    ja fail
    inc ecx
    cmp ecx, 16
    jb .print_loop

    ; Small anti-disassembly island (never executed).
    jmp short .after_junk
    db 0xe8,0xff,0xff,0xff,0x7f,0x0f,0x0b,0xeb,0xf7
.after_junk:

    ; Reversible input permutation:
    ; state[(5*i+7)&15] = rol8(input[i] + 17*i + 0x23, 3)
    lea rdi, [rel vm_state]
    xor ecx, ecx
.permute:
    mov al, byte [rbx+rcx]
    mov edx, ecx
    imul edx, edx, 17
    add al, dl
    add al, 0x23
    rol al, 3
    lea edx, [rcx+rcx*4+7]
    and edx, 15
    mov byte [rdi+rdx], al
    inc ecx
    cmp ecx, 16
    jb .permute

    ; Decrypt VM blob. Key update depends on the recovered plaintext byte:
    ; plain = encrypted XOR key
    ; key = rol8(key + plain + 0x3d, 3) XOR 0xa7
    lea rsi, [rel vm_blob]
    lea rdi, [rel vm_code]
    mov ecx, VM_BYTES
    mov r8b, 0xd3
.decrypt_vm:
    mov al, byte [rsi]
    xor al, r8b
    mov byte [rdi], al
    add r8b, al
    add r8b, 0x3d
    rol r8b, 3
    xor r8b, 0xa7
    inc rsi
    inc rdi
    dec ecx
    jnz .decrypt_vm

    ; VM context
    lea rbx, [rel vm_state]       ; 16 virtual byte registers
    lea r12, [rel vm_code]        ; program counter
    mov r13d, VM_INSNS            ; instructions remaining
    mov r15d, 0x6d2b79f5          ; junk/mutation accumulator

vm_loop:
    test r13d, r13d
    jz vm_done

    ; Fetch/decode operands before mutating the instruction.
    movzx r10d, byte [r12]
    movzx r8d,  byte [r12+1]
    movzx r9d,  byte [r12+2]
    movzx r11d, byte [r12+3]

    xor r8d, 0x5a
    and r8d, 15
    sub r9d, 0x39

    ; Rolling junk state, then erase current decoded instruction in memory.
    rol r15d, 5
    xor r15d, r11d
    add r15d, r13d
    mov edx, r15d
    xor edx, 0xa5c39e71
    mov dword [r12], edx

    ; Decode opcode and indirect-dispatch.
    mov eax, r10d
    xor eax, 0xa7
    imul eax, eax, 5
    add eax, 3
    and eax, 7

    add r12, 4
    dec r13d
    lea rdx, [rel handlers]
    jmp qword [rdx+rax*8]

vm_xori:
    xor byte [rbx+r8], r9b
    jmp vm_loop

vm_addi:
    add byte [rbx+r8], r9b
    jmp vm_loop

vm_roli:
    mov al, byte [rbx+r8]
    mov cl, r9b
    and cl, 7
    rol al, cl
    mov byte [rbx+r8], al
    jmp vm_loop

vm_xorr:
    and r9d, 15
    mov al, byte [rbx+r9]
    xor byte [rbx+r8], al
    jmp vm_loop

vm_addr:
    and r9d, 15
    mov al, byte [rbx+r9]
    add byte [rbx+r8], al
    jmp vm_loop

vm_subr:
    and r9d, 15
    mov al, byte [rbx+r9]
    sub byte [rbx+r8], al
    jmp vm_loop

vm_swap:
    and r9d, 15
    mov al, byte [rbx+r8]
    mov dl, byte [rbx+r9]
    mov byte [rbx+r8], dl
    mov byte [rbx+r9], al
    jmp vm_loop

vm_not:
    not byte [rbx+r8]
    jmp vm_loop

vm_done:
    ; Opaque predicate: x^2 and x have identical parity, so this cannot fail.
    mov eax, r15d
    mov edx, eax
    imul edx, eax
    xor eax, edx
    test eax, 1
    jnz fail

    ; Load 128-bit state and apply a reversible post-mix.
    mov r8d,  dword [rbx]
    mov r9d,  dword [rbx+4]
    mov r10d, dword [rbx+8]
    mov r11d, dword [rbx+12]

    mov eax, r9d
    rol eax, 5
    add r8d, eax

    mov eax, r8d
    ror eax, 7
    xor r10d, eax

    mov eax, r10d
    rol eax, 11
    add r11d, eax

    mov eax, r11d
    ror eax, 13
    xor r9d, eax

    ; Reconstruct four expected words independently and accumulate differences.
    xor r14d, r14d

    mov edx, 0xd1da04df
    xor edx, 0xfe4cb38d
    rol edx, 7
    add edx, 0xc3068578
    xor edx, r8d
    or r14d, edx

    mov edx, 0xe5dd91bf
    xor edx, 0x2e29cc64
    rol edx, 11
    add edx, 0xec4c2f91
    xor edx, r9d
    or r14d, edx

    mov edx, 0x6cc72861
    xor edx, 0x8fe32631
    rol edx, 17
    add edx, 0x04faf2e7
    xor edx, r10d
    or r14d, edx

    mov edx, 0x765ee1aa
    xor edx, 0xaacbf430
    rol edx, 23
    add edx, 0xfe391e38
    xor edx, r11d
    or r14d, edx

    ; Indirect final decision, intentionally patchable.
    lea rax, [rel success]
    lea rdx, [rel fail]
    test r14d, r14d
    cmovne rax, rdx
    jmp rax

success:
    mov eax, SYS_WRITE
    mov edi, 1
    lea rsi, [rel good_msg]
    mov edx, good_len
    syscall

    mov eax, SYS_EXIT
    xor edi, edi                 ; sys_exit(0) address must stay stable when patched
    syscall

fail:
    mov eax, SYS_WRITE
    mov edi, 1
    lea rsi, [rel bad_msg]
    mov edx, bad_len
    syscall

    mov eax, SYS_EXIT
    mov edi, 1
    syscall
