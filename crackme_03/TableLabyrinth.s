; ---------------------------------------------------------------------------
; TableLabyrinth.s
; x86-64 Linux crackme, NASM syntax, no libc.
;
; Technique principale:
;   - pas de hash standard (MD5/SHA/etc.)
;   - pas de machine virtuelle / bytecode
;   - réseau de contraintes par tables, S-box et permutations croisées
;   - 32 contraintes globales, chaque contrainte lit les 16 caractères dans
;     un ordre différent et mélange l'état avec XOR/ADD/ROL/S-box.
;
; Build:
;   nasm -f elf64 TableLabyrinth.s -o TableLabyrinth.o
;   ld -s -o TableLabyrinth TableLabyrinth.o
; ---------------------------------------------------------------------------

BITS 64
default rel

section .text
global _start

_start:
    ; write(1, prompt, prompt_len)
    mov eax, 1
    mov edi, 1
    lea rsi, [prompt]
    mov edx, prompt_len
    syscall

    ; read(0, buf, 64)
    xor eax, eax
    xor edi, edi
    lea rsi, [buf]
    mov edx, 64
    syscall

    ; Accept exactly 16 bytes, or 16 bytes followed by '\n'
    cmp rax, 16
    je .length_ok
    cmp rax, 17
    jne fail
    cmp byte [buf + 16], 10
    jne fail

.length_ok:
    ; r12d = accumulated failure mask
    xor r12d, r12d

    ; Table bases
    lea r14, [seeds]
    lea r15, [targets]
    lea rsi, [perm_table]
    lea rdi, [key_table]
    lea rbp, [op_table]
    lea rdx, [buf]
    lea r13, [sbox_table]

    xor r8d, r8d                ; check index c = 0

.outer_check:
    cmp r8d, 32
    jge .finish_checks

    mov bl, [r14 + r8]          ; state = seeds[c]
    xor r9d, r9d                ; step j = 0

.inner_step:
    cmp r9d, 16
    jge .one_check_done

    ; offset = c * 16 + j
    mov r10, r8
    shl r10, 4
    add r10, r9

    ; v = input[perm[offset]] xor key[offset]
    movzx r11d, byte [rsi + r10]
    mov al, [rdx + r11]
    xor al, [rdi + r10]

    ; v = rol8(v, (op & 7) + 1)
    movzx ecx, byte [rbp + r10]
    and cl, 7
    inc cl
    rol al, cl

    ; state = either state + v or state xor v
    test byte [rbp + r10], 8
    jz .xor_state
    add bl, al
    jmp .after_main_mix

.xor_state:
    xor bl, al

.after_main_mix:
    ; state ^= sbox[(state ^ v) & 0x0f]
    movzx r11d, bl
    xor r11b, al
    and r11d, 0x0f
    xor bl, [r13 + r11]

    ; state = rol8(state, ((op >> 4) & 7) + 1)
    movzx ecx, byte [rbp + r10]
    shr cl, 4
    and cl, 7
    inc cl
    rol bl, cl

    inc r9d
    jmp .inner_step

.one_check_done:
    ; accumulate mismatches, do not stop at first failure
    mov al, bl
    xor al, [r15 + r8]
    movzx eax, al
    or r12d, eax

    inc r8d
    jmp .outer_check

.finish_checks:
    test r12d, r12d
    jnz fail

success:
    mov eax, 1
    mov edi, 1
    lea rsi, [msg_ok]
    mov edx, msg_ok_len
    syscall

    mov eax, 60
    xor edi, edi
    syscall

fail:
    mov eax, 1
    mov edi, 1
    lea rsi, [msg_bad]
    mov edx, msg_bad_len
    syscall

    mov eax, 60
    mov edi, 1
    syscall

